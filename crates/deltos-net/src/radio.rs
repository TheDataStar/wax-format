//! E3, the box's own Wi-Fi: the access point phones join
//! (docs/box-radio-and-boot.md, Track E §6).
//!
//! The radio settings are four values, all chosen by whoever sets the box
//! up (provisioning, then the `configure_ap` action). **None has a default
//! here**: a default network name or password would be the same on every
//! box, and the country decides which channels are legal, so the box never
//! guesses it.
//!
//! The generated `hostapd.conf` holds the passphrase, so it is written
//! readable by its owner only ([`crate::render::write`]).

use std::fmt;

use crate::registry::{NetError, Result};

/// A secret that never prints. `Debug` and `Display` show `[redacted]`
/// (privilege boundary rule 12: Wi-Fi passwords are never logged).
#[derive(Clone, PartialEq, Eq)]
pub struct Secret(String);

impl Secret {
    pub fn new(s: impl Into<String>) -> Self {
        Secret(s.into())
    }
    /// The value itself, for the one place that needs it (`hostapd.conf`).
    pub fn expose(&self) -> &str {
        &self.0
    }
}

impl fmt::Debug for Secret {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("[redacted]")
    }
}

impl fmt::Display for Secret {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("[redacted]")
    }
}

/// The hotspot's radio settings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Radio {
    /// The network name phones see: 1 to 32 bytes (IEEE 802.11).
    pub ssid: String,
    /// WPA2 passphrase: 8 to 63 printable ASCII characters (IEEE 802.11i).
    pub passphrase: Secret,
    /// Where the box is, as an ISO 3166-1 alpha-2 code (`GB`, `KE`, `US`).
    /// It sets which channels and power levels are legal there.
    pub country: String,
    /// The 2.4 GHz channel, 1 to 13. Whether it is legal in `country` is the
    /// kernel's regulatory database's call; `hostapd` refuses an illegal one.
    pub channel: u8,
}

impl Radio {
    pub fn validate(&self) -> Result<()> {
        let n = self.ssid.len();
        if n == 0 || n > 32 {
            return Err(NetError::Invalid(format!("network name must be 1 to 32 bytes, not {n}")));
        }
        if self.ssid.chars().any(|c| c.is_control()) {
            return Err(NetError::Invalid("network name contains a control character".into()));
        }
        let p = self.passphrase.expose();
        if !(8..=63).contains(&p.len()) || !p.bytes().all(|b| (0x20..=0x7e).contains(&b)) {
            return Err(NetError::Invalid("Wi-Fi password must be 8 to 63 printable ASCII characters".into()));
        }
        let c = self.country.as_bytes();
        // "00" is the "world" placeholder some drivers report: not a place.
        if c.len() != 2 || !c.iter().all(|b| b.is_ascii_uppercase()) {
            return Err(NetError::Invalid(format!("country {:?} must be a two-letter ISO 3166-1 code, upper case", self.country)));
        }
        if !(1..=13).contains(&self.channel) {
            return Err(NetError::Invalid(format!("channel {} must be a 2.4 GHz channel, 1 to 13", self.channel)));
        }
        Ok(())
    }

    /// The `hostapd` settings for `interface`.
    ///
    /// * WPA2-Personal with AES (CCMP) only: every phone in use supports it,
    ///   and TKIP is broken. WPA3 is left for a later change measured against
    ///   real handsets (Commander's hold on hardware testing).
    /// * 2.4 GHz (`hw_mode=g`, with 802.11n): the band every phone and the
    ///   Pi's built-in radio support, and the longest reach across a room.
    /// * No control socket: nothing on the box drives `hostapd` at run time,
    ///   so there is no socket to attack. A change rewrites this file and
    ///   restarts it.
    /// * Devices on the hotspot cannot reach each other directly
    ///   (`ap_isolate`): learners' phones talk to the box, not to one another.
    pub fn hostapd_conf(&self, interface: &str) -> String {
        format!(
            "# Generated by deltos-net from the network registry. Do not edit: changes are overwritten.\n\
             # docs/box-radio-and-boot.md. Holds the Wi-Fi password: readable by root only.\n\
             interface={interface}\n\
             driver=nl80211\n\
             # network name: {name}\n\
             ssid2={ssid}\n\
             utf8_ssid=1\n\
             country_code={country}\n\
             ieee80211d=1\n\
             hw_mode=g\n\
             channel={channel}\n\
             ieee80211n=1\n\
             wmm_enabled=1\n\
             auth_algs=1\n\
             wpa=2\n\
             wpa_key_mgmt=WPA-PSK\n\
             rsn_pairwise=CCMP\n\
             wpa_passphrase={pass}\n\
             ap_isolate=1\n\
             ignore_broadcast_ssid=0\n",
            name = self.ssid,
            ssid = hex(&self.ssid),
            country = self.country,
            channel = self.channel,
            pass = self.passphrase.expose(),
        )
    }
}

/// hostapd's `ssid2=` takes the name as hex when unquoted: any bytes,
/// quotes and backslashes included, with nothing to escape.
fn hex(s: &str) -> String {
    s.bytes().map(|b| format!("{b:02x}")).collect()
}
