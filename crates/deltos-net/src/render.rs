//! The `dnsmasq` and `nftables` settings generated from the registry
//! (docs/box-network-plan.md §2–§5).
//!
//! Generation is a pure function of the registry, so the same registry
//! always gives byte-identical files. Four files, written atomically
//! (temporary file, then rename) into one directory:
//!
//! | File | Holds | Picked up |
//! |---|---|---|
//! | `dnsmasq.conf` | Zones, wildcard answers, upstreams, the hotspot's DHCP | On `dnsmasq` restart |
//! | `names.d/names` | Approved names that point at another device | **At once**: `dnsmasq` watches the directory (`hostsdir`) |
//! | `dhcp-hosts.d/reservations` | Fixed addresses on the hotspot | **At once** (`dhcp-hostsdir`) |
//! | `uplink.nft` | Whether hotspot devices may reach the internet through the box | When the firewall is reloaded |
//!
//! So approving a name or a reservation needs no restart (Track E §23.3);
//! only a change of mode, upstream or uplink sharing does.
//!
//! Rules every generated `dnsmasq.conf` keeps:
//! * **No query log, ever** (`log-queries` is never written; contract §16).
//!   Pack hostnames carry a person's partition, so a query log would be a
//!   reading log.
//! * **Every name under `deltos.lan` and `deltos-packs.lan` is the box** —
//!   a wildcard, because pack hostnames are made per person per browser.
//!   `deltd` refuses any it did not issue.
//! * **Those zones never leave the box** (`local=`), and with no upstream
//!   every other name is answered "no such name" at once.
//! * **DHCP only on the box's own hotspot**, never on a joined network.

use std::fmt::Write as _;
use std::net::Ipv4Addr;
use std::path::{Path, PathBuf};

use crate::connectivity;
use crate::registry::{mask, Mode, NetError, Registry, Result, Target, PACK_ZONE, SERVICE_ZONE};

/// The generated files, as text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rendered {
    pub dnsmasq_conf: String,
    pub names: String,
    pub dhcp_hosts: String,
    pub nftables: String,
}

/// Paths inside the settings directory.
pub struct Layout {
    pub dir: PathBuf,
}

impl Layout {
    pub fn new(dir: impl Into<PathBuf>) -> Self {
        Layout { dir: dir.into() }
    }
    pub fn dnsmasq_conf(&self) -> PathBuf {
        self.dir.join("dnsmasq.conf")
    }
    pub fn names_dir(&self) -> PathBuf {
        self.dir.join("names.d")
    }
    pub fn dhcp_hosts_dir(&self) -> PathBuf {
        self.dir.join("dhcp-hosts.d")
    }
    pub fn leases(&self) -> PathBuf {
        self.dir.join("leases")
    }
    pub fn nftables(&self) -> PathBuf {
        self.dir.join("uplink.nft")
    }
}

/// What a running box must do for a change to take effect.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Reload {
    pub restart_dnsmasq: bool,
    pub reload_firewall: bool,
}

pub fn render(reg: &Registry, layout: &Layout) -> Result<Rendered> {
    let s = reg.settings()?;
    let box_ip = s.box_address();
    let hotspot = matches!(s.mode, Mode::Hotspot { .. });
    // Phones' internet checks come to the box only when the box gives them no
    // internet (plan §6). With sharing on, they reach the real hosts.
    let answer_checks = !(hotspot && s.uplink_sharing);
    let p = |x: &Path| x.display().to_string();

    let mut c = String::new();
    c.push_str("# Generated by deltos-net from the network registry. Do not edit: changes are overwritten.\n");
    c.push_str("# docs/box-network-plan.md. Query logging is deliberately absent (contract §16).\n\n");
    let iface = match &s.mode {
        Mode::Hotspot { interface, .. } | Mode::Joined { interface, .. } => interface,
    };
    let _ = writeln!(c, "interface={iface}");
    c.push_str("bind-dynamic\n");
    let _ = writeln!(c, "listen-address={box_ip}");
    c.push_str("no-hosts\nno-resolv\ndomain-needed\nbogus-priv\nstop-dns-rebind\n");
    for zone in [SERVICE_ZONE, PACK_ZONE] {
        // the box's own zones: answered here, never forwarded, and allowed to
        // resolve to the box's private address despite stop-dns-rebind
        let _ = writeln!(c, "local=/{zone}/");
        let _ = writeln!(c, "address=/{zone}/{box_ip}");
        let _ = writeln!(c, "rebind-domain-ok=/{zone}/");
    }
    if answer_checks {
        c.push_str("\n# phones' internet checks, answered by deltd (plan §6)\n");
        for h in connectivity::hosts() {
            let _ = writeln!(c, "address=/{h}/{box_ip}");
        }
        let (h, a) = connectivity::WINDOWS_DNS_CHECK;
        let _ = writeln!(c, "address=/{h}/{a}");
    }
    c.push('\n');
    if s.upstream_dns.is_empty() {
        c.push_str("# offline: every other name is answered \"no such name\" at once\n");
        c.push_str("address=/#/\n");
    } else {
        for u in &s.upstream_dns {
            let _ = writeln!(c, "server={u}");
        }
    }
    let _ = writeln!(c, "\nhostsdir={}", p(&layout.names_dir()));

    if let Mode::Hotspot { prefix_len, .. } = &s.mode {
        let (net, _) = s.hotspot_net().expect("hotspot");
        let m = mask(*prefix_len);
        // the box's own address is never handed out
        let mut first = Ipv4Addr::from(u32::from(net) + 1);
        if first == box_ip {
            first = Ipv4Addr::from(u32::from(net) + 2);
        }
        let last = Ipv4Addr::from((u32::from(net) | !m) - 1);
        let netmask = Ipv4Addr::from(m);
        c.push_str("\n# DHCP on the box's own hotspot only (plan §3.1)\n");
        // the whole subnet; dnsmasq never hands out an address in use,
        // its own included. Lease time: dnsmasq's default.
        let _ = writeln!(c, "dhcp-range={first},{last},{netmask}");
        let _ = writeln!(c, "dhcp-option=option:router,{box_ip}");
        let _ = writeln!(c, "dhcp-option=option:dns-server,{box_ip}");
        let _ = writeln!(c, "dhcp-option=option:domain-search,{SERVICE_ZONE}");
        c.push_str("dhcp-authoritative\n");
        let _ = writeln!(c, "dhcp-hostsdir={}", p(&layout.dhcp_hosts_dir()));
        let _ = writeln!(c, "dhcp-leasefile={}", p(&layout.leases()));
    } else {
        c.push_str("\n# joined to another network: no DHCP here, ever (plan §3.2)\n");
    }

    let mut names = String::from("# Generated by deltos-net. Approved names that point at another device.\n");
    for n in reg.names()? {
        if let Target::Address(a) = n.target {
            let _ = writeln!(names, "{a} {}", n.name);
        }
    }
    let mut dhcp_hosts = String::from("# Generated by deltos-net. Fixed addresses on the hotspot.\n");
    if hotspot {
        for r in reg.reservations()? {
            let _ = writeln!(dhcp_hosts, "{},{},{}", r.mac, r.address, r.label);
        }
    }

    let mut nft = String::from("# Generated by deltos-net. Internet sharing for hotspot devices (plan §3.1).\n");
    nft.push_str("table inet deltos_uplink\ndelete table inet deltos_uplink\n");
    nft.push_str("table inet deltos_uplink {\n  chain forward {\n    type filter hook forward priority 0; policy drop;\n");
    match (&s.mode, &s.uplink_interface, s.uplink_sharing) {
        (Mode::Hotspot { interface, .. }, Some(up), true) => {
            let _ = writeln!(nft, "    iifname \"{interface}\" oifname \"{up}\" accept");
            let _ = writeln!(nft, "    iifname \"{up}\" oifname \"{interface}\" ct state established,related accept");
            nft.push_str("  }\n  chain postrouting {\n    type nat hook postrouting priority 100;\n");
            let _ = writeln!(nft, "    oifname \"{up}\" masquerade");
            nft.push_str("  }\n}\n");
        }
        _ => nft.push_str("    # sharing off: nothing is forwarded\n  }\n}\n"),
    }
    Ok(Rendered { dnsmasq_conf: c, names, dhcp_hosts, nftables: nft })
}

/// Render and write every file; returns which running services must reload.
/// Files whose content did not change are not touched.
pub fn write(reg: &Registry, layout: &Layout) -> Result<Reload> {
    let r = render(reg, layout)?;
    let io = |e: std::io::Error| NetError::Io(e.to_string());
    std::fs::create_dir_all(layout.names_dir()).map_err(io)?;
    std::fs::create_dir_all(layout.dhcp_hosts_dir()).map_err(io)?;
    let mut reload = Reload::default();
    if replace(&layout.dnsmasq_conf(), &r.dnsmasq_conf)? {
        reload.restart_dnsmasq = true;
    }
    replace(&layout.names_dir().join("names"), &r.names)?;
    replace(&layout.dhcp_hosts_dir().join("reservations"), &r.dhcp_hosts)?;
    if replace(&layout.nftables(), &r.nftables)? {
        reload.reload_firewall = true;
    }
    Ok(reload)
}

/// Atomically replace `path` with `text`; false if it already held it.
fn replace(path: &Path, text: &str) -> Result<bool> {
    if std::fs::read_to_string(path).ok().as_deref() == Some(text) {
        return Ok(false);
    }
    let tmp = path.with_extension("tmp~");
    let io = |e: std::io::Error| NetError::Io(format!("{}: {e}", path.display()));
    std::fs::write(&tmp, text).map_err(io)?;
    std::fs::rename(&tmp, path).map_err(io)?;
    Ok(true)
}
